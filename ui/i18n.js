let lang = (navigator.languages || [navigator.language || 'en']).some(l => /^fr\b/i.test(l)) ? 'fr' : 'en';
function setLang(next) {
  if (!STRINGS[next] || next === lang) return false;
  lang = next; document.documentElement.lang = lang; translate(); return true;
}
function t(key, params = {}) {
  let text = STRINGS[lang][key] ?? STRINGS.fr[key] ?? key;
  if (typeof text !== 'string') return text;
  for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, value);
  return text;
}
function errorText(error) {
  const code = typeof error === 'string' ? error : error?.error || error?.code;
  return code && STRINGS[lang][`error.${code}`] ? t(`error.${code}`, error?.params || {}) : t('error.unexpected');
}
function translate(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(e => { e.title = t(e.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-label]').forEach(e => { e.setAttribute('aria-label', t(e.dataset.i18nLabel)); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(e => { e.placeholder = t(e.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-alt]').forEach(e => { e.alt = t(e.dataset.i18nAlt); });
}
document.documentElement.lang = lang;
